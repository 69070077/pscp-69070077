"""Increase//Decrease"""
def main():
    """Increase//Decrease"""
    num1 = float(input())
    num2 = float(input())
    num3 = float(input())
    if num3 > num2 > num1  :
        print("increasing")
    elif num3 < num2  < num1:
        print("decreasing")
    else:
        print("neither")
main()
